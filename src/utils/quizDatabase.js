/**
 * Gets the daily selection of 12 questions.
 * Uses the current date string as a stable seed to ensure 
 * the same questions are returned throughout the day.
 */
export const getDailyQuestions = () => {
  const today = new Date().toISOString().split('T')[0]; // "YYYY-MM-DD"
  
  // Simple deterministic shuffle based on the date string
  let seed = 0;
  for (let i = 0; i < today.length; i++) {
    seed += today.charCodeAt(i);
  }

  // Copy and shuffle
  const shuffled = [...QUIZ_POOL].sort((a, b) => {
    const randomA = Math.sin(seed + a.id.charCodeAt(1)) * 10000;
    const randomB = Math.sin(seed + b.id.charCodeAt(1)) * 10000;
    return (randomA - Math.floor(randomA)) - (randomB - Math.floor(randomB));
  });

  // Return exactly 12 questions
  return shuffled.slice(0, 12);
};
